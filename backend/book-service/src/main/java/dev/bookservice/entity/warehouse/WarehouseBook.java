package dev.bookservice.entity.warehouse;

import lombok.*;
import org.springframework.data.relational.core.mapping.Table;

import java.time.LocalDateTime;

/**
 * Сущность связи книги и склада (складские запасы).
 * <p>
 * Представляет запись в таблице {@code WAREHOUSES_BOOKS} и хранит информацию
 * о количестве конкретных книг, находящихся на определенном складе.
 * Является ассоциативной сущностью, реализующей связь "многие-ко-многим"
 * между книгами и складами с дополнительным атрибутом количества.
 * <p>
 * Для автоматической генерации геттеров, сеттеров, конструкторов и билдера
 * используются аннотации Lombok.
 */
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
@Builder
@Table(name = "WAREHOUSES_BOOKS")
public class WarehouseBook {

    /**
     * Идентификатор книги.
     * <p>Вместе с {@code warehouseId} образует составной первичный ключ или уникальный индекс,
     * гарантирующий, что для одной книги на одном складе существует только одна запись о запасе.
     */
    private Long bookId;

    /**
     * Идентификатор склада.
     * <p>Ссылается на сущность {@link Warehouse}. Определяет место хранения данной партии товара.
     */
    private Long warehouseId;

    /**
     * Текущее количество единиц книги на данном складе.
     * <p>Должно быть неотрицательным числом. Обновляется при поступлении новых поставок
     * или оформлении заказов на отгрузку.
     */
    private Long quantity;

    /**
     * Дата и время первой регистрации книги на этом складе.
     * <p>Заполняется автоматически при создании записи о наличии товара.
     */
    private LocalDateTime createdAt;

    /**
     * Дата и время последнего изменения количества товара.
     * <p>Обновляется при каждом изменении поля {@code quantity} (пополнение или списание).
     * Используется для аудита складских операций.
     */
    private LocalDateTime modifiedAt;
}