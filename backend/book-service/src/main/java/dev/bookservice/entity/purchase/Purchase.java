package dev.bookservice.entity.purchase;

import lombok.*;
import org.springframework.data.annotation.Id;
import org.springframework.data.relational.core.mapping.Table;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * Сущность покупки (транзакции/заказа).
 * <p>
 * Представляет запись в таблице {@code PURCHASES} и хранит данные
 * о приобретении книги у конкретного поставщика, включая финансовые
 * параметры и временные метки жизненного цикла заказа.
 * <p>
 * Для автоматической генерации геттеров, сеттеров, конструкторов и билдера
 * используются аннотации Lombok.
 */
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
@Builder
@Table(name = "PURCHASES")
public class Purchase {

    /**
     * Уникальный идентификатор покупки.
     * <p>Является первичным ключом таблицы {@code PURCHASES}.
     */
    @Id
    private Long purchaseId;

    /**
     * Идентификатор приобретенной книги.
     * <p>Ссылается на сущность книги. Используется для связи с каталогом товаров
     * и восстановления детальной информации о позиции при формировании отчётов.
     */
    private Long bookId;

    /**
     * Идентификатор поставщика.
     * <p>Ссылается на сущность {@code Provider}. Указывает контрагента,
     * ответственного за отгрузку или поставку данной партии товара.
     */
    private Long providerId;

    /**
     * Количество экземпляров книги в данной покупке.
     * <p>Должно быть положительным числом. Используется для расчёта итоговой суммы
     * и контроля складских остатков.
     */
    private Long quantity;

    /**
     * Итоговая финансовая сумма покупки.
     * <p>Рассчитывается на основе цены товара и количества. Хранится в формате {@link BigDecimal}
     * для обеспечения точности финансовых операций и избежания ошибок округления.
     */
    private BigDecimal totalSum;

    /**
     * Дата и время создания покупки (оформления заказа).
     * <p>Заполняется автоматически при сохранении сущности.
     */
    private LocalDateTime createdAt;

    /**
     * Дата и время прибытия/доставки покупки.
     * <p>Может оставаться {@code null} до момента фактического получения товара
     * на склад или подтверждения доставки клиенту. Обновляется на этапе обработки заказа.
     */
    private LocalDateTime arrivedAt;
}